class TestScriptCompatibility:
    """Import smoke-tests and cross-script data compatibility checks."""

    # -----------------------------------------------------------------------
    def test_all_scripts_importable(self, tmp_path, monkeypatch):
        """
        A selection of key pipeline scripts must be importable without crashing.
        Scripts that replace sys.stdout at module level are excluded; only
        stdlib-safe scripts are tested here.
        """
        # These scripts use only stdlib or have safe import-time behaviour
        safe_scripts = [
            "compliance_report",
            "validate_config",
            "deployment_readiness",
            "health_check",
            "run_pipeline",
        ]

        monkeypatch.setenv("DATA_DIR", str(tmp_path))

        for script_name in safe_scripts:
            # Do NOT pop from sys.modules — some scripts replace sys.stdout at
            # import time (health_check, pipeline_status) and are already cached
            # by conftest.py. Re-importing under capsys would corrupt stdout.
            try:
                mod = importlib.import_module(script_name)
            except SystemExit:
                # Some scripts call sys.exit() at module scope when run directly;
                # a SystemExit from import is still an import, not a crash.
                pass
            except Exception as exc:
                pytest.fail(
                    f"Script '{script_name}' raised {type(exc).__name__} on import: {exc}"
                )

    # -----------------------------------------------------------------------
    def test_compliance_report_integrates_with_session_data(self, tmp_path):
        """
        compliance_report.load_ppv_from_csv() must correctly parse a session CSV
        that was written in the same format produced by the collect service,
        and compliance check results must reflect the actual PPV values.
        """
        sys.modules.pop("compliance_report", None)
        import compliance_report as cr

        # Write a fake session CSV as the collect service would produce
        csv_path = tmp_path / "session_2026-03-04.csv"
        rows = [
            {"timestamp": "2026-03-04T10:00:00Z", "device_id": "m5-01",
             "ppv": "0.05", "rms": "0.02", "label": "normal"},
            {"timestamp": "2026-03-04T10:00:01Z", "device_id": "m5-01",
             "ppv": "0.15", "rms": "0.06", "label": "normal"},
            {"timestamp": "2026-03-04T10:00:02Z", "device_id": "m5-01",
             "ppv": "0.50", "rms": "0.20", "label": "soil_creep"},
        ]
        with open(csv_path, "w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=rows[0].keys())
            writer.writeheader()
            writer.writerows(rows)

        ppv_values = cr.load_ppv_from_csv(str(csv_path))
        assert len(ppv_values) == 3, (
            f"Expected 3 PPV values, got {len(ppv_values)}"
        )
        assert abs(ppv_values[0] - 0.05) < 1e-9
        assert abs(ppv_values[2] - 0.50) < 1e-9

        # Run a DIN compliance check — 0.50 mm/s exceeds Category I (0.3 mm/s)
        results = cr.run_compliance_checks(ppv_values, ["din"])
        assert len(results) == 1
        din_result = results[0]
        assert din_result["standard_key"] == "din"
        # Category I threshold = 0.3; 0.50 exceeds it → overall_compliant must be False
        assert din_result["overall_compliant"] is False, (
            "PPV of 0.50 mm/s exceeds DIN 4150-3 Category I — should be non-compliant"
        )
        assert din_result["max_ppv"] == pytest.approx(0.50, abs=1e-9)

    # -----------------------------------------------------------------------
    def test_deployment_readiness_matches_actual_files(self, tmp_path, monkeypatch):
        """
        deployment_readiness.run_checks() must correctly detect files that DO exist
        and must not report false positives (FAIL) for those files.

        We patch ROOT to a controlled tmp directory, create the files that the
        check expects, and verify that run_checks() passes for those items.
        """
        sys.modules.pop("deployment_readiness", None)
        import deployment_readiness as dr

        # Build the minimal directory tree that deployment_readiness expects
        fake_root = tmp_path / "repo"
        asset_dir = fake_root / "app" / "assets" / "ml"
        scripts_dir = fake_root / "scripts"
        asset_dir.mkdir(parents=True)
        scripts_dir.mkdir(parents=True)

        # Create the files that fatal checks look for
        files_to_create = [
            asset_dir / "precursor_classifier.tflite",
            asset_dir / "ml_anomaly_model.tflite",
            asset_dir / "precursor_scaler.json",
            scripts_dir / "run_pipeline.py",
            scripts_dir / "health_check.py",
            fake_root / "docker-compose.yml",
            fake_root / "docker-compose.collect.yml",
            fake_root / "docker-compose.train.yml",
        ]
        for p in files_to_create:
            p.write_bytes(b"placeholder content so size > 0")

        # Patch JSON files to be valid JSON
        (asset_dir / "precursor_scaler.json").write_text(
            json.dumps({"mean": [0.0] * 17, "scale": [1.0] * 17}),
            encoding="utf-8",
        )

        # Monkeypatch dr.ROOT and derived dirs so checks point at our fake repo
        monkeypatch.setattr(dr, "ROOT", fake_root)
        monkeypatch.setattr(dr, "ASSET_DIR", asset_dir)
        monkeypatch.setattr(dr, "SCRIPTS_DIR", scripts_dir)
        monkeypatch.setattr(dr, "DATA_DIR", fake_root / "data" / "field")

        # Rebuild CHECKS with patched constants (lambdas captured OLD values;
        # we must rebuild them using the monkeypatched attrs)
        from typing import List, Tuple

        new_checks: List[Tuple[str, callable, bool]] = [
            ("ML model: precursor_classifier.tflite",
             lambda: dr.check_file_exists(dr.ASSET_DIR / "precursor_classifier.tflite"), True),
            ("ML model: ml_anomaly_model.tflite",
             lambda: dr.check_file_exists(dr.ASSET_DIR / "ml_anomaly_model.tflite"), True),
            ("Scaler:   precursor_scaler.json",
             lambda: dr.check_json_parseable(dr.ASSET_DIR / "precursor_scaler.json"), True),
            ("Script:   run_pipeline.py",
             lambda: dr.check_file_exists(dr.SCRIPTS_DIR / "run_pipeline.py"), True),
            ("Script:   health_check.py",
             lambda: dr.check_file_exists(dr.SCRIPTS_DIR / "health_check.py"), True),
            ("Compose:  docker-compose.yml",
             lambda: dr.check_file_exists(dr.ROOT / "docker-compose.yml"), True),
            ("Compose:  docker-compose.collect.yml",
             lambda: dr.check_file_exists(dr.ROOT / "docker-compose.collect.yml"), True),
            ("Compose:  docker-compose.train.yml",
             lambda: dr.check_file_exists(dr.ROOT / "docker-compose.train.yml"), True),
        ]
        monkeypatch.setattr(dr, "CHECKS", new_checks)

        results, failures = dr.run_checks()

        # All fatal checks should pass — no false positives for files we created
        failed_labels = [r["label"] for r in results if not r["ok"] and r["fatal"]]
        assert failures == 0, (
            f"Expected 0 fatal failures for files that exist, "
            f"but got {failures}: {failed_labels}"
        )

        # Every result for a fatal check must be ok=True
        for r in results:
            if r["fatal"]:
                assert r["ok"], (
                    f"Fatal check '{r['label']}' reported FAIL for a file that exists: "
                    f"{r['detail']}"
                )
