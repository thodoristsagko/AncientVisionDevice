class TestPipelineDataFlow:
    """Data schema / feature consistency checks across the pipeline."""

    # -----------------------------------------------------------------------
    def test_generate_to_collect_format(self, tmp_path):
        """
        The collector ingest endpoint expects a JSON payload that includes 'ppv',
        'rms', 'freq', and a 'label' field.  The synthetic data generated by
        generate_precursor_data must produce the same set of numeric features,
        confirming the schemas are compatible without actually running TF training.
        """
        # Define the collector's required ingest fields (from docker/collect/app.py)
        collector_required = {"rms", "ppv", "freq", "crest", "centroid",
                              "kurtosis", "stalta", "arias", "cav", "label"}

        # The generated feature names cover all DSP outputs
        generated_fields = set(EXPECTED_FEATURE_NAMES)

        # Collector fields (excluding label) must be a subset of generated features
        missing = (collector_required - {"label", "temp", "psdSlope"}) - generated_fields
        assert not missing, (
            f"Collector fields not present in generated features: {missing}"
        )

    # -----------------------------------------------------------------------
    def test_feature_count_consistency(self, tmp_path):
        """
        All 17 features must be present in:
          1. EXPECTED_FEATURE_NAMES (mirrors generate_precursor_data.py)
          2. A scaler JSON with the correct number of mean/scale entries
          3. A config JSON with input_dim == 17
        """
        # Build a fake scaler consistent with 17 features
        scaler = {
            "mean": [0.0] * EXPECTED_FEATURE_COUNT,
            "scale": [1.0] * EXPECTED_FEATURE_COUNT,
            "feature_names": EXPECTED_FEATURE_NAMES,
        }
        assert len(scaler["mean"]) == EXPECTED_FEATURE_COUNT
        assert len(scaler["scale"]) == EXPECTED_FEATURE_COUNT
        assert len(scaler["feature_names"]) == EXPECTED_FEATURE_COUNT

        # Build a fake config consistent with 17 features
        config = {
            "input_dim": EXPECTED_FEATURE_COUNT,
            "output_dim": EXPECTED_CLASS_COUNT,
            "feature_names": EXPECTED_FEATURE_NAMES,
            "class_names": EXPECTED_CLASS_NAMES,
        }
        assert config["input_dim"] == EXPECTED_FEATURE_COUNT
        assert len(config["feature_names"]) == EXPECTED_FEATURE_COUNT

    # -----------------------------------------------------------------------
    def test_label_encoding_consistency(self, tmp_path):
        """
        Labels in generated data must map to model class indices consistently:
          normal=0, soil_creep=1, crack_propagation=2, imminent_failure=3.
        """
        label_to_index = {name: i for i, name in enumerate(EXPECTED_CLASS_NAMES)}

        assert label_to_index["normal"] == 0
        assert label_to_index["soil_creep"] == 1
        assert label_to_index["crack_propagation"] == 2
        assert label_to_index["imminent_failure"] == 3

        # Verify the CLASS_NAMES list in the config JSON preserves this ordering
        config = {"class_names": EXPECTED_CLASS_NAMES}
        for idx, name in enumerate(config["class_names"]):
            assert label_to_index[name] == idx, (
                f"Class {name!r} should have index {label_to_index[name]}, "
                f"got {idx} from config class_names list"
            )

    # -----------------------------------------------------------------------
    def test_csv_roundtrip(self, tmp_path):
        """
        Writing a sample dict to CSV and reading it back must preserve all
        field values (within float precision).
        """
        sample = {
            "rms": 0.12345,
            "ppv": 0.34567,
            "freq": 15.0,
            "crest": 3.14,
            "centroid": 25.0,
            "kurtosis": 2.718,
            "stalta": 1.5,
            "arias": 0.001,
            "cav": 0.05,
            "temp": 22.0,
            "psdSlope": -2.0,
            "ppv_trend": 1.05,
            "freq_trend": 0.98,
            "kurtosis_trend": 1.1,
            "stalta_trend": 1.0,
            "cusum_max": 0.3,
            "autoencoder_score": 0.15,
            "label": "normal",
        }

        csv_path = tmp_path / "test_session.csv"
        fieldnames = list(sample.keys())

        # Write
        with open(csv_path, "w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerow(sample)

        # Read back
        with open(csv_path, newline="", encoding="utf-8") as fh:
            reader = csv.DictReader(fh)
            rows = list(reader)

        assert len(rows) == 1
        row = rows[0]
        assert row["label"] == "normal"
        for key in EXPECTED_FEATURE_NAMES:
            assert abs(float(row[key]) - sample[key]) < 1e-5, (
                f"CSV roundtrip mismatch for field {key!r}: "
                f"wrote {sample[key]}, read {float(row[key])}"
            )


