# ---------------------------------------------------------------------------
# Constants mirrored from generate_precursor_data.py (without executing it)
# ---------------------------------------------------------------------------

EXPECTED_FEATURE_NAMES = [
    "rms", "ppv", "freq", "crest", "centroid", "kurtosis", "stalta",
    "arias", "cav", "temp", "psdSlope",
    "ppv_trend", "freq_trend", "kurtosis_trend", "stalta_trend",
    "cusum_max", "autoencoder_score",
]
EXPECTED_FEATURE_COUNT = 17

EXPECTED_CLASS_NAMES = ["normal", "soil_creep", "crack_propagation", "imminent_failure"]
EXPECTED_CLASS_COUNT = 4

# ---------------------------------------------------------------------------
# Helper: load run_pipeline cleanly in a tmp_path context
# ---------------------------------------------------------------------------

def _load_pipeline(tmp_path: Path, monkeypatch):
    """Import run_pipeline with DATA_DIR and ASSETS_DIR pointed at tmp_path."""
    monkeypatch.setenv("DATA_DIR", str(tmp_path / "data"))
    sys.modules.pop("run_pipeline", None)
    import run_pipeline as rp
    rp.DATA_DIR = tmp_path / "data"
    rp.TRIGGER_FILE = rp.DATA_DIR / ".retrain_trigger"
    rp.ASSETS_DIR = tmp_path / "assets"
    return rp


