class TestPipelineErrorHandling:
    """Error paths in run_pipeline and validate_config."""

    # -----------------------------------------------------------------------
    def test_missing_data_dir_exits_nonzero(self, tmp_path, monkeypatch):
        """
        When no field data directory exists, dry_run() must return 1 (error).
        The pipeline must not proceed to training when data is absent.
        """
        rp = _load_pipeline(tmp_path, monkeypatch)
        rp.DATA_DIR.mkdir(parents=True, exist_ok=True)
        rp.TRIGGER_FILE.touch()
        # field/ deliberately NOT created — simulates a fresh deployment with no data

        result = rp.dry_run()
        assert result == 1, (
            "dry_run() must return 1 when the field data directory is missing"
        )

    # -----------------------------------------------------------------------
    def test_corrupted_model_detected(self, tmp_path):
        """
        validate_config.validate_scaler() must report an error when a scaler JSON
        is syntactically corrupt (truncated / not valid JSON).
        """
        sys.modules.pop("validate_config", None)
        import validate_config as vc

        # Write a corrupt (truncated) JSON file
        corrupt_path = tmp_path / "precursor_classifier_scaler.json"
        corrupt_path.write_text('{"mean": [1.0, 2.0', encoding="utf-8")  # truncated

        data, err = vc._load_json(str(corrupt_path))
        assert data is None, "Corrupt JSON must fail to load"
        assert err is not None, "Error string must be returned for corrupt JSON"
        assert len(err) > 0

    # -----------------------------------------------------------------------
    def test_scaler_dimension_mismatch_detected(self, tmp_path):
        """
        validate_config.validate_scaler() must flag a dimension mismatch between
        'mean' (17 elements) and 'std'/'scale' (wrong number of elements).
        """
        sys.modules.pop("validate_config", None)
        import validate_config as vc

        # Scaler with mismatched mean/std lengths
        scaler_data = {
            "mean": list(range(17)),
            "std": list(range(10)),   # wrong: should be 17
        }

        errors = vc.validate_scaler(scaler_data)
        assert errors, "validate_scaler must report errors for dimension-mismatched scaler"
        combined = " ".join(errors)
        # Should mention lengths
        assert "17" in combined or "10" in combined or "length" in combined.lower(), (
            f"Error message should mention the length mismatch: {errors}"
        )

    # -----------------------------------------------------------------------
    def test_scaler_missing_keys_detected(self, tmp_path):
        """
        validate_config.validate_scaler() must report errors when 'mean' or 'std'
        keys are entirely absent from the scaler JSON.
        """
        sys.modules.pop("validate_config", None)
        import validate_config as vc

        incomplete_scaler = {"feature_names": EXPECTED_FEATURE_NAMES}
        errors = vc.validate_scaler(incomplete_scaler)
        assert errors, "validate_scaler must report errors for missing 'mean'/'std' keys"
        combined = " ".join(errors)
        assert "mean" in combined or "std" in combined, (
            f"Error should mention missing key names: {errors}"
        )


